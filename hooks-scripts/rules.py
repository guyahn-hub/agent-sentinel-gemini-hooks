"""
Antigravity Global Security Rules

전역 보안 게이트에서 사용하는 보안 규칙 정의 파일입니다.

역할:
- 위험 명령 정의
- 민감 파일/경로 정의
- 보호 대상 정의
- 승인 및 작업 범위 정책 정의

주의:
이 파일 자체는 도구 실행을 차단하지 않습니다.
실제 차단은 security_gate.py가 담당합니다.
"""


# ============================================================
# 1. 위험 명령
# ============================================================

DANGEROUS_COMMAND_PATTERNS = [
    # 파일/디렉터리 대량 삭제
    r"\brm\s+-rf\s+[/~]",
    r"\bdel\s+/s\s+/q\b",
    r"\brmdir\s+/s\s+/q\b",

    # 디스크 관련
    r"\bformat\s+[a-zA-Z]:",
    r"\bdiskpart\b",

    # 시스템 종료/재부팅
    r"\bshutdown\b",
    r"\breboot\b",

    # Git 파괴적 작업
    r"\bgit\s+push\s+--force\b",
    r"\bgit\s+reset\s+--hard\b",
    r"\bgit\s+clean\s+-[^\n]*f",
]


# ============================================================
# 2. 민감 파일
# ============================================================

SENSITIVE_FILE_PATTERNS = [
    # 환경변수 / 비밀정보
    r"(^|[\\/])\.env($|[\\/])",
    r"(^|[\\/])\.env\.[^\\/]+$",

    # 일반적인 비밀키 / 인증정보
    r"(^|[\\/])credentials?\.(json|yaml|yml|toml)$",
    r"(^|[\\/])secrets?\.(json|yaml|yml|toml)$",

    # SSH / 개인키
    r"(^|[\\/])\.ssh[\\/]",
    r"\.(pem|key|p12|pfx)$",
]


# ============================================================
# 3. 보호해야 할 파일
# ============================================================

PROTECTED_FILE_PATTERNS = [
    # Antigravity 전역 설정
    r"(^|[\\/])\.gemini[\\/]",
    r"(^|[\\/])GEMINI\.md$",

    # Git 핵심 설정
    r"(^|[\\/])\.git[\\/]",
]


# ============================================================
# 4. 위험한 파일 작업
# ============================================================

DANGEROUS_FILE_OPERATIONS = {
    "delete": True,
    "overwrite": True,
    "rename": True,
}


# ============================================================
# 5. 승인 관련 정책
# ============================================================

# 승인되지 않은 파일 변경을 기본적으로 허용하지 않는 정책.
#
# 실제 승인 상태를 확인하는 기능은 security_gate.py에서
# 단계적으로 구현합니다.

REQUIRE_APPROVAL_FOR_FILE_CHANGES = True

REQUIRE_APPROVAL_FOR_FILE_DELETION = True

REQUIRE_APPROVAL_FOR_CONFIGURATION_CHANGES = True


# ============================================================
# 6. 작업 범위 정책
# ============================================================

# 사용자가 승인한 작업 범위를 벗어난 변경을 방지합니다.
#
# 실제 범위 비교 기능은 security_gate.py에서 구현합니다.

REQUIRE_APPROVED_SCOPE = True


# ============================================================
# 7. 불확실한 작업
# ============================================================

# 보안 검사를 정상적으로 수행할 수 없으면 차단합니다.

DENY_ON_SECURITY_CHECK_ERROR = True

DENY_ON_INVALID_HOOK_INPUT = True


# ============================================================
# 8. 로그 정책
# ============================================================

LOG_ALLOWED_ACTIONS = True

LOG_BLOCKED_ACTIONS = True

LOG_SECURITY_CHECK_FAILURES = True


# ============================================================
# 3.5 보안 핵심 파일 (직접 수정 차단 대상)
# ============================================================

SECURITY_CORE_FILE_PATTERNS = [
    r"(^|[\\/])security_gate\.py$",
    r"(^|[\\/])rules\.py$",
    r"(^|[\\/])protocol_manager\.py$",
    r"(^|[\\/])hooks\.json$",
    r"(^|[\\/])GEMINI\.md$",
]
